export function t(settings, key) {
  return messages[settings.language]?.[key] || messages.en[key] || key;
}

export function applyTranslations(settings, root = document) {
  root.querySelectorAll("[data-i18n]").forEach((node) => {
    node.textContent = t(settings, node.dataset.i18n);
  });
}
